-- Q12. Give the total weekly Sales value with Date and ProductId
--      Use ROLLUP to pull data in hierarchical order

SELECT Date, ProductId, 
       SUM(Sales) AS Total_Sales
FROM FactTable
GROUP BY ROLLUP(Date, ProductId)
ORDER BY Date, ProductId

-- To check the week 
SELECT DATEPART(week, Date) AS week_num,
       ProductId,
       SUM(Sales) AS Total_Sales
FROM FactTable
GROUP BY ROLLUP(DATEPART(week, Date), ProductId)
ORDER BY week_num, ProductId

