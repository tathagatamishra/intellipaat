-- Q11. Create a stored procedure to fetch the result
--      according to the Product_Type from ProductTable

CREATE PROCEDURE GetProductByName
       @Product_Type VARCHAR(50)
AS
BEGIN
       SELECT * FROM ProductTable
       WHERE Product_Type = @Product_Type
END

-- Execute
EXEC GetProductByName 'Coffee'
EXEC GetProductByName 'Espresso'
EXEC GetProductByName 'Herbal Tea'
EXEC GetProductByName 'Tea'

-- Using function
CREATE FUNCTION GetProductByType
       (@Product_Type VARCHAR(50))
RETURNS TABLE
AS
RETURN
       (SELECT * FROM ProductTable
        WHERE Product_Type = @Product_Type)

-- Call the UDF
SELECT * FROM GetProductByType('Coffee')

